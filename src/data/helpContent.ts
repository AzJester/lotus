// ============================================================================
// Help documents. Every Notes database carries "Help > About This Database"
// and "Help > Using This Database" documents (ABOUT_DOCS), and the Lotus Notes
// Help database opened with F1 holds the general topics (HELP_TOPICS). The
// bodies are written in the voice of the classic Notes online help and use
// the lightweight markup described on HelpDoc.
// ============================================================================

/** Lightweight markup rendered by the app: blank line = paragraph break;
 *  "## " heading; "- " bullet; table rows written "a | b | c" (first row is the header);
 *  **bold** inline. Nothing else. */
export interface HelpDoc {
  id: string;
  title: string;
  body: string;
}

export type HelpDbKey =
  | "mail"
  | "calendar"
  | "todo"
  | "addressbook"
  | "journal"
  | "discussion"
  | "directory"
  | "help"
  | "outbox";

/** Builds a help document. Each row is one line of markup; "" is a blank line. */
function doc(id: string, title: string, ...rows: string[]): HelpDoc {
  return { id, title, body: rows.join("\n") };
}

